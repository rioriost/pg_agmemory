def _case(
    number: int,
    category: str,
    language: Literal["en", "ja"],
    *,
    timeline: tuple[tuple[str, str], ...],
    question: str,
    answer: str | None,
    keep: tuple[int, ...],
    sources: tuple[int, ...] = (),
    forbidden: tuple[str, ...] = (),
) -> AgentMemoryCase:
    case_id = f"unseen-{number:02d}"
    return AgentMemoryCase(
        case_id=case_id,
        category=category,
        language=language,
        events=tuple(
            Event(event_id=f"{case_id}-e{index}", occurred_at=timestamp, text=text)
            for index, (timestamp, text) in enumerate(timeline, 1)
        ),
        question=question,
        expected_answer=answer,
        expected_keep_ids=tuple(f"{case_id}-e{index}" for index in keep),
        required_source_ids=tuple(f"{case_id}-e{index}" for index in sources),
        forbidden_answers=forbidden,
    )


